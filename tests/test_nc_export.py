"""
Exporting CNC jobs: the "NC file with comments" choice in the save dialog
writes comments describing the job at the top of the file.
"""

import os
import re
import shutil
import sys
import tempfile
import time
import unittest
from unittest import mock

from PyQt6 import QtWidgets

from FlatCAMApp import App
from FlatCAMObj import FlatCAMCNCjob

INCH = 25.4


class NCExportTestCase(unittest.TestCase):

    def setUp(self):
        self.app = QtWidgets.QApplication.instance() or QtWidgets.QApplication(sys.argv)
        self.fc = App(user_defaults=False)
        self.library = self.fc.tool_library
        # Isolate with the 0.8mm end mill: feed 200, plunge 60 mm/min
        self.tool = self.library.get_tool(2)
        self.tool.update(name="End mill (0.8mm)", feed=200.0, plunge=60.0, spindle=10000)
        self.fc.defaults["cutting_operations"]["isolation"].update(tool=2, cutz=-0.1)
        self.fc.defaults["cutting_job_end"].update(z_end=15.0, return_to_origin=True,
                                                   split=True, segment_length=2.0)
        self.tmpdir = tempfile.mkdtemp()

    def tearDown(self):
        shutil.rmtree(self.tmpdir)

    def wait_for(self, name, timeout=20):
        end = time.time() + timeout
        while time.time() < end:
            self.app.processEvents()
            obj = self.fc.collection.get_by_name(name)
            if obj is not None:
                return obj
            time.sleep(0.05)
        self.fail("%s was not created" % name)

    def isolation_job(self):
        self.fc.open_gerber('tests/gerber_files/simple1.gbr')
        self.fc.collection.get_by_name('simple1.gbr').isolate(passes=1, combine=True)
        self.wait_for('simple1.gbr_iso').generatecncjob()
        return self.wait_for('simple1.gbr_iso_cnc')

    def export(self, job, name, comments):
        path = os.path.join(self.tmpdir, name)
        job.export_gcode(path, comments=comments)
        with open(path) as f:
            return f.read()

    def test_isolation_comments(self):
        job = self.isolation_job()
        text = self.export(job, "iso.nc", comments=True)
        comments = text.splitlines()[:30]
        self.assertTrue(comments[0].startswith("(G-CODE GENERATED BY FLATCAM"))
        for expected in ("(Name: simple1.gbr_iso_cnc)",
                         "(Type: G-code from Geometry)",
                         "(Source: simple1.gbr_iso)",
                         "(Units: IN)",
                         "(TOOL: End mill [0.8mm])",  # No parentheses inside a comment
                         "(TOOL DIAMETER: %.4g in)" % (0.8 / INCH),
                         "(Feedrate_XY: %.4g in/min)" % (200.0 / INCH),
                         "(Feedrate_Z: %.4g in/min)" % (60.0 / INCH),
                         "(Z_Cut: %.4g in)" % (-0.1 / INCH),
                         "(Z End: %.4g in)" % (15.0 / INCH),
                         "(X,Y End: 0, 0)",
                         "(Max cut length: %.4g in)" % (2.0 / INCH),
                         "(Spindle Speed: 10000 RPM)"):
            self.assertIn(expected, comments)
        self.assertTrue(any(re.match(r"\(Created on \w+, \d+ \w+ \d{4} at \d\d:\d\d\)", c)
                            for c in comments))

        # The ranges are those of the cuts, not the trip back to X0 Y0
        xmin, ymin, xmax, ymax = self.cut_bounds(job)
        self.assertIn("(X range: %10.4f ... %10.4f  in)" % (xmin, xmax), comments)
        self.assertIn("(Y range: %10.4f ... %10.4f  in)" % (ymin, ymax), comments)
        self.assertGreater(xmin, 0)

    @staticmethod
    def cut_bounds(job):
        bounds = [g["geom"].bounds for g in job.gcode_parsed if g["kind"][0] == "C"]
        return (min(b[0] for b in bounds), min(b[1] for b in bounds),
                max(b[2] for b in bounds), max(b[3] for b in bounds))

    def test_comments_only_add_lines_at_the_top(self):
        job = self.isolation_job()
        with_comments = self.export(job, "a.nc", comments=True)
        plain = self.export(job, "b.gcode", comments=False)
        self.assertNotIn("(Name:", plain)
        self.assertTrue(with_comments.endswith(plain))
        header = with_comments[:-len(plain)].splitlines()
        self.assertTrue(all(l == "" or (l.startswith("(") and l.endswith(")")
                                        and l.count("(") == 1 and l.count(")") == 1)
                            for l in header))

    def test_drilling_comments_list_each_bit(self):
        for bit in self.library.drill_bits():
            bit.update(plunge=40.0, spindle=None)
        self.fc.open_excellon('tests/excellon_files/case1.drl')
        exc = self.fc.collection.get_by_name('case1.drl')
        self.fc.collection.set_active('case1.drl')
        exc.ui.tools_table.selectAll()
        exc.on_create_cncjob_button_click()
        job = self.wait_for('case1.drl_cnc')
        comments = self.export(job, "drill.nc", comments=True).splitlines()
        self.assertIn("(Type: G-code from Excellon)", comments)
        tools = [c for c in comments if c.startswith("(TOOL T")]
        self.assertTrue(tools)
        holes = sum(int(re.search(r"(\d+) holes", c).group(1)) for c in tools)
        self.assertEqual(holes, len(exc.drills))
        self.assertIn("(  Feedrate_Z: %.4g in/min, Spindle Speed: not set)" % (40.0 / INCH),
                      comments)
        self.assertFalse(any(c.startswith("(Max cut length") for c in comments))

    def dialog_export(self, job, typed_name, chosen_filter):
        self.fc.collection.set_all_inactive()
        self.fc.collection.set_active(job.options["name"])
        self.app.processEvents()
        path = os.path.join(self.tmpdir, typed_name)
        with mock.patch.object(QtWidgets.QFileDialog, "getSaveFileName",
                               return_value=(path, chosen_filter)) as dialog:
            job.on_exportgcode_button_click()
        filters = dialog.call_args[0][3]
        self.assertTrue(filters.startswith(FlatCAMCNCjob.NC_FILTER))
        return path

    def test_dialog_nc_choice_adds_comments_and_extension(self):
        job = self.isolation_job()
        path = self.dialog_export(job, "board", FlatCAMCNCjob.NC_FILTER)
        with open(path + ".nc") as f:
            self.assertTrue(f.readline().startswith("(G-CODE GENERATED BY FLATCAM"))

    def test_dialog_other_choice_has_no_comments(self):
        job = self.isolation_job()
        path = self.dialog_export(job, "board.gcode", FlatCAMCNCjob.EXPORT_FILTERS[1])
        with open(path) as f:
            self.assertNotIn("GENERATED BY FLATCAM", f.read())

    def test_dialog_cancel_writes_nothing(self):
        job = self.isolation_job()
        with mock.patch.object(QtWidgets.QFileDialog, "getSaveFileName", return_value=("", "")):
            job.on_exportgcode_button_click()
        self.assertEqual(os.listdir(self.tmpdir), [])

    def assert_ascii(self, path):
        with open(path, "rb") as f:
            data = f.read()
        bad = [b for b in data if not (32 <= b < 127 or b in b"\r\n\t")]
        self.assertEqual(bad, [], "bytes other than plain ASCII in %s" % path)
        return data

    def test_output_is_plain_ascii(self):
        self.tool["name"] = "V-bit 30° Ø0.1mm – fine"
        job = self.isolation_job()
        path = os.path.join(self.tmpdir, "ascii.nc")
        job.export_gcode(path, comments=True)
        data = self.assert_ascii(path)
        self.assertIn(b"(TOOL: V-bit 30deg dia 0.1mm - fine)", data)

    def test_prepended_and_appended_gcode_are_plain_ascii(self):
        messages = []
        self.fc.inform.connect(messages.append)
        job = self.isolation_job()
        job.options["dwell"] = True  # The other way the G-code is written
        path = os.path.join(self.tmpdir, "typed.nc")
        job.export_gcode(path, preamble="(Start: résumé 中)\nG00 Z5 ",
                         postamble="M05 (Done — 25°C)\nM30\n", comments=True)
        data = self.assert_ascii(path)
        self.assertIn(b"(Start: resume )", data)
        self.assertIn(b"G00 Z5 ", data)
        self.assertIn(b"M05 (Done - 25degC)", data)
        self.assertTrue(data.rstrip().endswith(b"M30"))
        self.assertIn(b"G4 P", data)
        self.assertTrue(any("plain ASCII" in m for m in messages))

    def test_plain_ascii_text_is_kept_exactly_and_no_warning(self):
        messages = []
        self.fc.inform.connect(messages.append)
        job = self.isolation_job()
        job.options["dwell"] = False  # Written exactly as generated
        path = os.path.join(self.tmpdir, "plain.gcode")
        job.export_gcode(path, preamble="G90\t(abs)", postamble="M30\n")
        with open(path) as f:
            self.assertEqual(f.read(), "G90\t(abs)\n" + job.gcode + "M30\n")
        self.assertFalse(any("plain ASCII" in m for m in messages))

    def test_shell_write_gcode_is_plain_ascii(self):
        job = self.isolation_job()
        path = os.path.join(self.tmpdir, "shell.gcode")
        self.fc.exec_command_test('write_gcode "%s" "%s" -preamble "(° start)" -postamble "(end é)"'
                                  % (job.options["name"], path.replace("\\", "/")))
        data = self.assert_ascii(path)
        self.assertIn(b"(deg start)", data)
        self.assertIn(b"(end e)", data)
        self.assertTrue(job.get_gcode("(°)", "").isascii())

    def test_drill_change_message_is_plain_ascii(self):
        for bit in self.library.drill_bits():
            bit["name"] = "Drill %g mm (carbide)°" % bit["dia"]
        self.fc.open_excellon('tests/excellon_files/case1.drl')
        exc = self.fc.collection.get_by_name('case1.drl')
        self.fc.collection.set_active('case1.drl')
        exc.ui.tools_table.selectAll()
        exc.on_create_cncjob_button_click()
        gcode = self.wait_for('case1.drl_cnc').gcode
        msgs = [l for l in gcode.splitlines() if l.startswith("(MSG")]
        self.assertTrue(msgs)
        for line in msgs:
            self.assertTrue(line.isascii())
            self.assertEqual(line.count("("), 1)
            self.assertEqual(line.count(")"), 1)

    def test_old_saved_coordinate_format_is_replaced(self):
        import json
        from camlib import CNCjob
        data_path = os.path.join(self.tmpdir, "profile")
        os.makedirs(data_path)
        with open(os.path.join(data_path, "defaults.json"), "w") as f:
            json.dump({"cncjob_coordinate_format": "X%.4fY%.4f", "units": "MM"}, f)
        self.fc.data_path = data_path
        self.fc.load_defaults()
        self.fc.propagate_defaults()
        self.assertEqual(self.fc.defaults["cncjob_coordinate_format"], "X%.4f Y%.4f")
        self.assertEqual(CNCjob.defaults["coordinate_format"], "X%.4f Y%.4f")
        self.assertEqual(self.fc.defaults["units"], "MM")

    def test_routing_starts_with_tool_change(self):
        job = self.isolation_job()
        gcode = [l.rstrip() for l in job.gcode.splitlines()]
        dia = job.job_info["tooldia"]
        travel = self.fc.collection.get_by_name('simple1.gbr_iso').options["travelz"]
        change = "G00 Z%.4f" % (15.0 / INCH)
        self.assertEqual(gcode[:19], [
            "G20", "G90", "G94", "", "G01 F%.2f" % (200.0 / INCH), "",
            "M5", change, "G00 X0.0000 Y0.0000", "T1", "M6",
            "(MSG, Change to End mill [0.8mm], Tool Dia = %.4f)" % dia, "M0", change, "",
            "M03 S10000", "G00 Z%.4f" % travel, "G01 F%.2f" % (200.0 / INCH),
            gcode[18]])
        self.assertTrue(gcode[18].startswith("G00 X"))  # Then off to the first cut
        self.assertEqual(sum(l == "M6" for l in gcode), 1)

    def test_drilling_changes_tool_for_every_bit(self):
        self.fc.open_excellon('tests/excellon_files/case1.drl')
        exc = self.fc.collection.get_by_name('case1.drl')
        exc.options["toolchange"] = False  # The Tool tab's bits are always changed
        self.fc.collection.set_active('case1.drl')
        exc.ui.tools_table.selectAll()
        exc.on_create_cncjob_button_click()
        job = self.wait_for('case1.drl_cnc')
        gcode = [l.rstrip() for l in job.gcode.splitlines()]
        bits = job.job_info["tools"]
        changes = [i for i, l in enumerate(gcode) if l == "M6"]
        self.assertEqual(len(changes), len(bits))
        self.assertLess(changes[0], min(i for i, l in enumerate(gcode) if l.startswith("G01 Z-")))
        change = "G00 Z%.4f" % exc.options["toolchangez"]
        for i, bit in zip(changes, bits):
            self.assertEqual(gcode[i - 4:i], ["M5", change, "G00 X0.0000 Y0.0000", "T%s" % bit["tool"]])
            self.assertEqual(gcode[i + 1], "(MSG, Change to %s, Tool Dia = %.4f)" % (bit["name"], bit["dia"]))
            self.assertEqual(gcode[i + 2:i + 5], ["M0", change, ""])
            self.assertTrue(gcode[i + 5].startswith("M03"))
        # The spindle only starts after the first bit is fitted
        self.assertFalse(any(l.startswith("M03") for l in gcode[:changes[0]]))

    def test_export_spaces_old_run_together_gcode(self):
        job = self.isolation_job()
        job.gcode = "G21\nG00 X0.0619Y0.5181\nG01X1.0000Y2.0000F100\n(MSG, X1Y2)\nM05\n"
        path = os.path.join(self.tmpdir, "old.nc")
        job.export_gcode(path, comments=True)
        with open(path) as f:
            text = f.read()
        self.assertIn("G00 X0.0619 Y0.5181\n", text)
        self.assertIn("G01 X1.0000 Y2.0000 F100\n", text)
        self.assertIn("(MSG, X1Y2)\n", text)  # Comments as they were

    def test_saved_job_keeps_settings_for_its_comments(self):
        job = self.isolation_job()
        before = self.export(job, "before.nc", comments=True).splitlines()
        loaded = FlatCAMCNCjob("loaded")
        loaded.from_dict(job.to_dict())
        loaded.options["name"] = job.options["name"]
        after = self.export(loaded, "after.nc", comments=True).splitlines()
        settings = [l for l in before if l.startswith(("(Feedrate", "(Z", "(X,Y", "(Max", "(Spindle"))]
        self.assertTrue(settings)
        for line in settings:
            self.assertIn(line, after)

    def test_job_from_older_project_still_exports(self):
        job = self.isolation_job()
        saved = job.to_dict()
        del saved["job_info"]
        job.job_info = None  # As a job loaded from an older project has
        job.from_dict(saved)
        comments = self.export(job, "old.nc", comments=True).splitlines()
        self.assertIn("(Name: simple1.gbr_iso_cnc)", comments)
        self.assertFalse(any(c.startswith("(Type:") for c in comments))


if __name__ == '__main__':
    unittest.main()
